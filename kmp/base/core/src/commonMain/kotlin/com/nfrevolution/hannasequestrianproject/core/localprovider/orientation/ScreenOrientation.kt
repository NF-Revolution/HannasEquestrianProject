package com.nfrevolution.hannasequestrianproject.core.localprovider.orientation

/**
 * Represents the screen orientation based on width and height dimensions.
 */
public enum class ScreenOrientation {
    /**
     * Portrait orientation: height is greater than or equal to width.
     */
    PORTRAIT,

    /**
     * Landscape orientation: width is greater than height.
     */
    LANDSCAPE
}
